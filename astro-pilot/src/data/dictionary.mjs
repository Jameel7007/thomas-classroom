export function defineDictionary(value) {
  if (!Array.isArray(value) || value.length < 1) throw new Error("Dictionary must contain at least one entry.");
  const words = new Set();
  const ids = new Set();
  for (const entry of value) {
    requireText(entry.word, "entry.word");
    requireText(entry.pronunciation, `${entry.word}.pronunciation`);
    requireLevel(entry.level, `${entry.word}.level`);
    requireText(entry.origin, `${entry.word}.origin`);
    if (words.has(entry.word)) throw new Error(`Duplicate dictionary word: ${entry.word}`);
    words.add(entry.word);
    if (!Array.isArray(entry.forms)) throw new Error(`${entry.word}.forms must be an array.`);
    if (entry.lesson && (!entry.lesson.label || !entry.lesson.route?.startsWith("/lessons/"))) {
      throw new Error(`${entry.word}.lesson must include a label and a clean lesson route.`);
    }
    if (!Array.isArray(entry.senses) || entry.senses.length < 2) throw new Error(`${entry.word} must contain at least two senses.`);
    for (const sense of entry.senses) {
      requireText(sense.id, `${entry.word}.sense.id`);
      requireLevel(sense.level, `${entry.word}/${sense.id}.level`);
      if (!DICTIONARY_PARTS.includes(sense.partOfSpeech)) throw new Error(`${entry.word}/${sense.id}: invalid part of speech.`);
      for (const field of ["label", "definition", "contrast"]) requireText(sense[field], `${entry.word}/${sense.id}.${field}`);
      if (!Array.isArray(sense.examples) || sense.examples.length < 2) throw new Error(`${entry.word}/${sense.id}: at least two examples are required.`);
      if (!Array.isArray(sense.chunks) || sense.chunks.length < 2) throw new Error(`${entry.word}/${sense.id}: at least two chunks are required.`);
      if (!Array.isArray(sense.synonyms)) throw new Error(`${entry.word}/${sense.id}.synonyms must be an array.`);
      const fullId = `${entry.word}/${sense.id}`;
      if (ids.has(fullId)) throw new Error(`Duplicate dictionary sense: ${fullId}`);
      ids.add(fullId);
    }
  }
  return Object.freeze(value);
}

